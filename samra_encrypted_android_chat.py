# -------------------- SEND MESSAGE --------------------

def on_send_clicked(_):
    text = message_input.value
    sender = sender_dropdown.value

    if not text or not text.strip():
        with details_output:
            clear_output(wait=True)
            print("Error: Please enter a message before sending.")
        return

    try:
        # Encrypt on the client before storing the packet
        encrypted_packet = encrypt_message(text)

        timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

        packet = {
            "sender": sender,
            "timestamp": timestamp,
            "nonce": encrypted_packet["nonce"],
            "ciphertext": encrypted_packet["ciphertext"]
        }

        # Store ciphertext rather than plaintext
        save_encrypted_history(packet)

        # Decrypt locally to demonstrate receiving/displaying
        decrypted_text = decrypt_message(encrypted_packet)

        show_chat_message(
            sender,
            decrypted_text,
            timestamp,
            "sent"
        )

        with details_output:
            clear_output(wait=True)
            print("Message encrypted successfully.")
            print("AES-256-GCM authentication verified.")
            print("Ciphertext saved to encrypted history.")
            print("\nEncrypted packet preview:")
            print(json.dumps(packet, indent=2))

        message_input.value = ""

    except Exception as error:
        logging.exception("Failed to send or encrypt message")
        with details_output:
            clear_output(wait=True)
            print("Message could not be processed.")
            print("Error type:", type(error).__name__)


