# -------------------- ENCRYPTION FUNCTIONS --------------------

def encrypt_message(plaintext):
    """Encrypt a message locally using AES-256-GCM."""

    if not isinstance(plaintext, str) or not plaintext.strip():
        raise ValueError("Message cannot be empty.")

    if len(plaintext) > MAX_MESSAGE_LENGTH:
        raise ValueError("Message is too long.")

    # A fresh 96-bit nonce for every encryption operation
    nonce = os.urandom(NONCE_SIZE)

    ciphertext = cipher.encrypt(
        nonce,
        plaintext.encode("utf-8"),
        None
    )

    return {
        "nonce": base64.b64encode(nonce).decode("ascii"),
        "ciphertext": base64.b64encode(ciphertext).decode("ascii")
    }


def decrypt_message(encrypted_packet):
    """Decrypt and authenticate a message locally."""

    nonce = base64.b64decode(
        encrypted_packet["nonce"], validate=True
    )

    ciphertext = base64.b64decode(
        encrypted_packet["ciphertext"], validate=True
    )

    if len(nonce) != NONCE_SIZE:
        raise ValueError("Invalid encryption nonce.")

    plaintext = cipher.decrypt(nonce, ciphertext, None)

    return plaintext.decode("utf-8")


# -------------------- MESSAGE STORAGE --------------------

def save_encrypted_history(packet):
    """
    Store encrypted message content and metadata.
    Plaintext is not written to the history file.
    """

    with history_lock:
        message_history.append(packet.copy())

        # The file contains ciphertext, not plaintext messages.
        with open("encrypted_message_history.json", "w") as file:
            json.dump(message_history, file, indent=2)


